import os
import numpy as np
import pandas as pd



#······································································#
# Contacts
#······································································#

def scm_res(
        input_pdb: os.PathLike,
        output_contacts: os.PathLike,
        chainid_1: str,
        chainid_2: str
    ) -> np.ndarray:
    """
    Generate an inter-chain residue contact map from SMOG atomistic contact outputs.

    This function parses a Structure-Based Model (SBM) PDB file to map atom serial
    numbers to their respective chain and residue identifiers. It then processes 
    the native contact pairs computed by SMOG (Structure-Based Models GroK) to 
    project atom-resolution interactions into a binary residue-resolution 
    inter-chain contact matrix.

    Parameters
    ----------
    input_pdb : os.PathLike
        Path to the input PDB file formatted for or generated by SMOG. Must contain 
        standard 'ATOM' or 'HETATM' records with valid chain identifiers, atom 
        serials, and residue sequence numbers.
    output_contacts : os.PathLike
        Path to the text-based SMOG contact output file. Expected to be whitespace-
        delimited with four columns representing interacting pairs: 
        [chain_number_1, atom_id_1, chain_number_2, atom_id_2].
    chainid_1 : str
        The 1-character PDB chain identifier for the first sequence axis (rows 
        of the returned matrix).
    chainid_2 : str
        The 1-character PDB chain identifier for the second sequence axis (columns 
        of the returned matrix).

    Returns
    -------
    np.ndarray
        A 2D boolean array of shape `(N, M)`, where `N` and `M` correspond to the 
        number of unique residue sequence numbers in `chainid_1` and `chainid_2`, 
        respectively. Elements are evaluated as `True` if at least one atomic 
        contact is detected between the corresponding residues, and `False` otherwise.

    Raises
    ------
    KeyError
        If an atom identifier present in the SMOG contact file cannot be resolved 
        within the parsed PDB dataframe index.
    IndexError
        If a residue sequence number (`res_seq`) from the PDB file minus 1 falls outside 
        the zero-indexed dimensions of the initialized contact matrix.

    Notes
    -----
    - **Chain Indexing:** SMOG factorizes chain IDs into 1-based integers based on 
      their sequential order of appearance in the PDB coordinate records. This behavior 
      is mirrored internally using `pandas.factorize`.
    - **Contact Symmetry:** The implementation explicitly evaluates both directional 
      permutations of the interaction tuple (i.e., `chainid_1` interacting with 
      `chainid_2` and vice versa) to capture all relevant inter-chain contacts.
    """

    # Parsing a residue mapping in SMOG input PDB
    residue_map = []
    with open(input_pdb, 'r') as f:
        for line in f:
            if line.startswith("ATOM") or line.startswith("HETATM"):
                try:
                    atom_serial = int(line[6:11].strip())
                    res_name = line[17:20].strip()
                    chain_id = line[21].strip()
                    res_seq = int(line[22:26].strip())
                    residue_map += [(chain_id, res_seq, atom_serial)]
                except ValueError:
                    continue
    residue_map = pd.DataFrame(residue_map, columns=['chainid', 'resid', 'atomid'])
    residue_map['chainno'] = pd.factorize(residue_map['chainid'])[0] + 1
    residue_map.set_index(['chainno','atomid'], inplace=True)

    # Loading SMOG output
    smog_output = pd.read_csv(
        output_contacts,
        delim_whitespace=True,
        names=['chainno_1', 'atomid_1', 'chainno_2', 'atomid_2']
    )

    # Initialising empty contact map
    chain_1_len = residue_map[residue_map['chainid'] == chainid_1]['resid'].nunique()
    chain_2_len = residue_map[residue_map['chainid'] == chainid_2]['resid'].nunique()
    smog_contacts = np.zeros((chain_1_len, chain_2_len), dtype=bool)

    # Looking for inter-chain AA contacts
    for _, row in smog_output.iterrows():
        cid_1, rid_1 = residue_map.loc[(row['chainno_1'], row['atomid_1'])]
        cid_2, rid_2 = residue_map.loc[(row['chainno_2'], row['atomid_2'])]

        if (cid_1 == chainid_1) & (cid_2 == chainid_2):
            smog_contacts[rid_1-1, rid_2-1] = True
        elif (cid_1 == chainid_2) & (cid_2 == chainid_1):
            smog_contacts[rid_2-1, rid_1-1] = True

    return smog_contacts
